const assert=require('node:assert/strict');
const M=require('../docs/workspace/model.js');
let s=M.initial();
assert.equal(s.cash,100000);
assert.throws(()=>M.trade(s,{symbol:'SPY',quantity:1,price:100,side:'sell'}),/Insufficient/);
assert.throws(()=>M.trade(s,{symbol:'SPY',quantity:10000,price:100,side:'buy'}),/Insufficient/);
s=M.trade(s,{symbol:'spy',quantity:10,price:100,side:'buy'});
assert.equal(s.cash,98999);
assert.equal(s.orders[0].mode,'simulation');
assert.equal(M.allocation(s).rows[0].quantity,10);
s=M.trade(s,{symbol:'SPY',quantity:10,price:120,side:'sell'});
assert.ok(Math.abs(s.cash-100197.8)<1e-8);
assert.equal(M.allocation(s).rows.length,0);
assert.throws(()=>M.settings(s,{fee:1001,holdout:30,benchmark:'SPY'}));
assert.equal(M.settings(s,{theme:'light',density:'compact'}).settings.theme,'light');
assert.equal(M.load(JSON.stringify(s)).cash,s.cash);
assert.throws(()=>M.load('{"version":2}'));
assert.equal(M.project('A research project').name,'A research project');
assert.equal(M.proposal('Mandate','Evidence and risk').status,'draft');
console.log('Workspace model tests passed');